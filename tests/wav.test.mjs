import {test,expect} from 'bun:test';
import {readFileSync} from 'node:fs';
import {metadata,wavBytes,readMetadata,DIGITAL_SOURCE_TYPE} from '../web/wav.mjs';
const fixture=JSON.parse(readFileSync(new URL('./fixtures/wav-metadata.json',import.meta.url),'utf8'));
const sha=bytes=>new Bun.CryptoHasher('sha256').update(bytes).digest('hex');
const samples=Float32Array.from({length:1001},(_,i)=>Math.sin(i*0.05)*1.2*(i%7===0?-1:1));
const tag=(bytes,at)=>String.fromCharCode(...bytes.subarray(at,at+4));

test('WAV bytes and metadata equal those of the Python package',()=>{
 const chunks=metadata({family:fixture.family,voice:fixture.voice});
 expect(chunks.length).toBe(fixture.metadataBytes);
 expect(sha(chunks)).toBe(fixture.metadataSha256);
 expect(sha(wavBytes(samples,24000,chunks))).toBe(fixture.wavSha256);
 expect(sha(wavBytes(samples,24000))).toBe(fixture.plainWavSha256);
 expect(sha(metadata({family:fixture.family,voice:fixture.voice,watermark:true}))).toBe(fixture.watermarkMetadataSha256);
});

test('the reader finds the metadata, and nothing in a plain file',()=>{
 const found=readMetadata(wavBytes(samples,24000,metadata({family:'kale',voice:'fresh-de-f01'})).buffer);
 expect(found).toEqual({aiGenerated:true,generator:'Designed Voices TTS',comment:'AI-generated speech (kale fresh-de-f01), generated by Designed Voices TTS. Check: python -m designed_tts.mark detect',digitalSourceType:DIGITAL_SOURCE_TYPE});
 expect(readMetadata(wavBytes(samples,24000).buffer)).toBe(null);
 expect(readMetadata(new TextEncoder().encode('ID3 not a wav').buffer)).toBe(null);
});

test('metadata chunks follow the canonical 44-byte header and the data chunk',()=>{
 const chunks=metadata({family:'voca64',voice:'fresh-en-f03'}),bytes=wavBytes(samples,24000,chunks),view=new DataView(bytes.buffer);
 expect([tag(bytes,0),tag(bytes,8),tag(bytes,12),tag(bytes,36)]).toEqual(['RIFF','WAVE','fmt ','data']);
 expect(view.getUint32(4,true)).toBe(bytes.length-8);
 const after=44+view.getUint32(40,true);
 expect(tag(bytes,after)).toBe('LIST');expect(tag(bytes,after+8)).toBe('INFO');
 const list=view.getUint32(after+4,true),pmx=after+8+list+(list%2);
 expect(tag(bytes,pmx)).toBe('_PMX');
 expect(pmx+8+view.getUint32(pmx+4,true)+(view.getUint32(pmx+4,true)%2)).toBe(bytes.length);
 const text=new TextDecoder().decode(chunks);
 expect(text).toContain('Designed Voices TTS');expect(text).toContain('AI-generated speech (voca64 fresh-en-f03), generated by Designed Voices TTS.');expect(text).not.toContain('AudioSeal');expect(text).toContain(DIGITAL_SOURCE_TYPE);
});

test('metadata takes printable ASCII model names only, never other text',()=>{
 expect(()=>metadata({family:'kale',voice:'Grüße'})).toThrow('INVALID_METADATA_TEXT');
 expect(metadata().length).toBeLessThan(fixture.metadataBytes);
});
