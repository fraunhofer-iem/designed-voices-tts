// 16-bit mono WAV of the outputs. Attenuated only if needed to avoid clipping. Unless marking is off, two
// standard metadata chunks follow the data chunk: RIFF LIST/INFO (software and a comment) and XMP
// (_PMX) with the IPTC digital source type for AI-generated media. They hold the generator, model
// and voice, never the entered text. The 44-byte header stays the canonical one. The same bytes as
// designed_tts.mark.metadata and wav_bytes in Python (tests/fixtures/wav-metadata.json).
export const GENERATOR='Designed Voices TTS';
export const DIGITAL_SOURCE_TYPE='http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia';

const ascii=text=>{if(!/^[\x20-\x7e]*$/.test(text))throw Error('INVALID_METADATA_TEXT');return Uint8Array.from(text,c=>c.charCodeAt(0));};
function chunk(tag,body){
 const bytes=new Uint8Array(8+body.length+(body.length%2)),view=new DataView(bytes.buffer);
 bytes.set(ascii(tag));view.setUint32(4,body.length,true);bytes.set(body,8);return bytes;
}
const join=parts=>{const out=new Uint8Array(parts.reduce((n,p)=>n+p.length,0));let at=0;for(const p of parts){out.set(p,at);at+=p.length;}return out;};

// The comment names the watermark only when the samples carry it (marking mode "watermark").
export function metadata({family=null,voice=null,watermark=false}={}){
 const model=[family,voice].filter(Boolean).join(' ');
 const comment='AI-generated speech'+(model?' ('+model+')':'')+', generated by '+GENERATOR+'.'+(watermark?' AudioSeal watermark, message DV.':'')+' Check: python -m designed_tts.mark detect';
 const info=join([ascii('INFO'),chunk('ISFT',join([ascii(GENERATOR),Uint8Array.of(0)])),chunk('ICMT',join([ascii(comment),Uint8Array.of(0)]))]);
 const xmp='<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'+
  '<rdf:Description rdf:about="" xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/" '+
  'xmlns:xmp="http://ns.adobe.com/xap/1.0/" Iptc4xmpExt:DigitalSourceType="'+DIGITAL_SOURCE_TYPE+'" xmp:CreatorTool="'+GENERATOR+'"/></rdf:RDF></x:xmpmeta>';
 return join([chunk('LIST',info),chunk('_PMX',ascii(xmp))]);
}

export function wavBytes(samples,sampleRate,extra=new Uint8Array(0)){
 const buffer=new ArrayBuffer(44+samples.length*2+extra.length),view=new DataView(buffer);
 const string=(at,text)=>{for(let i=0;i<text.length;i++)view.setUint8(at+i,text.charCodeAt(i));};
 string(0,'RIFF');view.setUint32(4,36+samples.length*2+extra.length,true);string(8,'WAVE');string(12,'fmt ');view.setUint32(16,16,true);view.setUint16(20,1,true);view.setUint16(22,1,true);view.setUint32(24,sampleRate,true);view.setUint32(28,sampleRate*2,true);view.setUint16(32,2,true);view.setUint16(34,16,true);string(36,'data');view.setUint32(40,samples.length*2,true);
 const peak=samples.reduce((a,b)=>Math.max(a,Math.abs(b)),.0001),gain=Math.min(1,.97/peak);
 for(let i=0;i<samples.length;i++)view.setInt16(44+2*i,Math.round(Math.max(-1,Math.min(1,samples[i]*gain))*32767),true);
 new Uint8Array(buffer,44+samples.length*2).set(extra);
 return new Uint8Array(buffer);
}

// What the metadata chunks of a WAV file say (the rule of designed_tts.mark.read_metadata), or null.
export function readMetadata(buffer){
 const bytes=new Uint8Array(buffer),view=new DataView(bytes.buffer,bytes.byteOffset,bytes.byteLength),tag=at=>String.fromCharCode(...bytes.subarray(at,at+4));
 if(bytes.length<12||tag(0)!=='RIFF'||tag(8)!=='WAVE')return null;
 const info={},text=(from,to)=>new TextDecoder().decode(bytes.subarray(from,to));let xmp=null;
 for(let at=12;at+8<=bytes.length;){
  const name=tag(at),size=view.getUint32(at+4,true),body=at+8;
  if(name==='LIST'&&tag(body)==='INFO')for(let sub=body+4;sub+8<=Math.min(body+size,bytes.length);){const length=view.getUint32(sub+4,true);info[tag(sub)]=text(sub+8,sub+8+length).replace(/\0+$/,'');sub+=8+length+(length%2);}
  else if(name==='_PMX')xmp=text(body,body+size);
  at=body+size+(size%2);
 }
 if(!Object.keys(info).length&&xmp===null)return null;
 const source=/DigitalSourceType="([^"]*)"/.exec(xmp||'')?.[1]??null,tool=/CreatorTool="([^"]*)"/.exec(xmp||'')?.[1]??null;
 return {aiGenerated:source===DIGITAL_SOURCE_TYPE||(info.ICMT||'').includes('AI-generated'),generator:info.ISFT||tool,comment:info.ICMT??null,digitalSourceType:source};
}
